function normalizeExtractedPdfText(text) {
  if (!text) return '';

  // 1. Remove Tatweel / Kashida (\u0640)
  let clean = text.replace(/\u0640/g, '');

  // 2. Normalize reversed / mangled question headers
  // E.g. ": 1 لؤئسملا" or "1 لؤسملا :" or "السؤال 1 :" or "1: السؤال"
  clean = clean.replace(/(?:\b|[\s:\(\)])(?:السؤال|سؤال|س|Q|Question|لؤسملا|لؤئسملا|لؤسملا|لؤشملأا)\s*:?\s*(\d+)\s*:?/gi, '\n\n#### السؤال $1 :\n');
  clean = clean.replace(/[:\s]*(\d+)\s*:?\s*(?:السؤال|سؤال|س|Q|Question|لؤسملا|لؤئسملا|لؤسملا|لؤشملأا)(?:\b|[\s:\(\)])/gi, '\n\n#### السؤال $1 :\n');

  // 3. Normalize Answer Key markers
  // E.g. ":ةحيحصلا الإجابة" or "الإجابة الصحيحة:"
  clean = clean.replace(/(?:الإجابة الصحيحة|اإلجابة الصحيحة|ةحيحصلا الإجابة|ةحيحصلا اإلجابة|ةحيحصلا الجابة|ةحيحصلا اجابة|ةحيحصلا الإجابة)\s*:?/gi, '\nالإجابة الصحيحة: ');

  // 4. Normalize Choice markers like "( أ (" or "( أ )" or "أ(" or "( أ "
  clean = clean.replace(/[\(\)\[\]]\s*([أبجدa-h1-8])\s*[\(\)\[\]]/gi, '\n($1) ');
  clean = clean.replace(/(^|\s+)[\(\)\[\]]?\s*([أبجدa-h1-8])\s*[\(\)\[\]](?=\s*[\u0600-\u06FFa-zA-Z0-9])/gi, '\n($2) ');

  return clean;
}

